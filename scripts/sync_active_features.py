#!/usr/bin/env python3
"""Generate the one-page active feature view from feature status files."""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FEATURES = ROOT / "docs" / "features"
OUTPUT = FEATURES / "active.md"
TERMINAL_STATES = {"accepted", "cancelled"}
FIELD = re.compile(r"^- (?P<name>[A-Za-z ]+): (?P<value>.+)$", re.MULTILINE)


def read_fields(path: Path) -> dict[str, str]:
    return {match.group("name").strip().lower().replace(" ", "_"): match.group("value").strip() for match in FIELD.finditer(path.read_text(encoding="utf-8"))}


def active_features() -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    for directory in sorted(FEATURES.glob("FTR-*")):
        status = directory / "status.md"
        feature = directory / "feature.md"
        if not directory.is_dir() or not status.is_file() or not feature.is_file():
            continue
        fields = read_fields(status)
        state = fields.get("state", "blocked: invalid status")
        if state in TERMINAL_STATES:
            continue
        title = feature.read_text(encoding="utf-8").splitlines()[0].removeprefix("# ").strip()
        rows.append({"id": directory.name, "title": title, "stage": fields.get("stage", "—"), "state": state, "issue": fields.get("github_issue", "—"), "next": fields.get("next_action", "—")})
    return rows


def render(rows: list[dict[str, str]]) -> str:
    lines = ["# Active features", "", "> Generated by `python scripts/sync_active_features.py`. Do not edit manually.", "", "Features remain active until `status.md` is `accepted` or `cancelled`. `merged` remains active until feature acceptance is confirmed.", ""]
    if not rows:
        return "\n".join(lines + ["No active features.", ""])
    lines += ["| Feature | Stage | State | Issue | Next action |", "|---|---|---|---|---|"]
    for row in rows:
        lines.append(f"| [{row['id']}]({row['id']}/feature.md) — {row['title']} | {row['stage']} | {row['state']} | {row['issue']} | {row['next']} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render(active_features())
    actual = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
    if args.check:
        if actual != expected:
            print("docs/features/active.md is stale; run python scripts/sync_active_features.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(expected, encoding="utf-8")
    print("Synced docs/features/active.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
